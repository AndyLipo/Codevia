BEGIN;

-- =========================================================
-- 1. ESQUEMAS
-- =========================================================

CREATE SCHEMA IF NOT EXISTS logistica;
CREATE SCHEMA IF NOT EXISTS transporte;


-- =========================================================
-- 2. LOGISTICA.HOJA_RUTA
-- =========================================================

CREATE SEQUENCE logistica.hoja_ruta_nro_seq
    START WITH 1
    INCREMENT BY 1
    NO CYCLE;

CREATE TABLE logistica.hoja_ruta (
    id_hoja_ruta INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nro_hoja_ruta VARCHAR(20) NOT NULL
        DEFAULT (
            'HR-' || LPAD(
                NEXTVAL('logistica.hoja_ruta_nro_seq'::REGCLASS)::TEXT,
                6,
                '0'
            )
        ),

    fecha_hoja_ruta DATE NOT NULL DEFAULT CURRENT_DATE,
    observaciones VARCHAR(1000),

    estado CHAR(1) NOT NULL DEFAULT 'A',

    usu_alta VARCHAR(20) NOT NULL,
    fec_alta TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usu_mod VARCHAR(20),
    fec_mod TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_hoja_ruta PRIMARY KEY (id_hoja_ruta),
    CONSTRAINT uq_hoja_ruta_nro UNIQUE (nro_hoja_ruta),
    CONSTRAINT ck_hoja_ruta_estado
        CHECK (estado IN ('A', 'I', 'E'))
);

ALTER SEQUENCE logistica.hoja_ruta_nro_seq
    OWNED BY logistica.hoja_ruta.nro_hoja_ruta;


-- =========================================================
-- 3. TRANSPORTE.VEHICULO
-- =========================================================

CREATE TABLE transporte.vehiculo (
    id_vehiculo INTEGER GENERATED BY DEFAULT AS IDENTITY,

    patente VARCHAR(15) NOT NULL,
    marca VARCHAR(50),
    modelo VARCHAR(50),
    anio INTEGER,
    capacidad_kg NUMERIC(12,2),
    observaciones VARCHAR(1000),

    estado CHAR(1) NOT NULL DEFAULT 'A',

    usu_alta VARCHAR(20) NOT NULL,
    fec_alta TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usu_mod VARCHAR(20),
    fec_mod TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_vehiculo PRIMARY KEY (id_vehiculo),
    CONSTRAINT uq_vehiculo_patente UNIQUE (patente),
    CONSTRAINT ck_vehiculo_estado
        CHECK (estado IN ('A', 'I', 'E')),
    CONSTRAINT ck_vehiculo_anio
        CHECK (anio IS NULL OR anio BETWEEN 1900 AND 2100),
    CONSTRAINT ck_vehiculo_capacidad
        CHECK (capacidad_kg IS NULL OR capacidad_kg > 0)
);


-- =========================================================
-- 4. TRANSPORTE.CONDUCTOR
-- =========================================================

CREATE TABLE transporte.conductor (
    legajo VARCHAR(20) NOT NULL,

    observaciones VARCHAR(1000),

    estado CHAR(1) NOT NULL DEFAULT 'A',

    usu_alta VARCHAR(20) NOT NULL,
    fec_alta TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usu_mod VARCHAR(20),
    fec_mod TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_conductor PRIMARY KEY (legajo),

    CONSTRAINT fk_conductor_recursos_humanos
        FOREIGN KEY (legajo)
        REFERENCES administracion.recursos_humanos (legajo),

    CONSTRAINT ck_conductor_estado
        CHECK (estado IN ('A', 'I', 'E'))
);


-- =========================================================
-- 5. LOGISTICA.DETALLE_HOJA_RUTA
-- =========================================================

CREATE TABLE logistica.detalle_hoja_ruta (
    id_detalle_hoja_ruta INTEGER GENERATED BY DEFAULT AS IDENTITY,

    id_hoja_ruta INTEGER NOT NULL,
    id_pedido INTEGER NOT NULL,

    observaciones VARCHAR(1000),

    estado CHAR(1) NOT NULL DEFAULT 'A',

    usu_alta VARCHAR(20) NOT NULL,
    fec_alta TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usu_mod VARCHAR(20),
    fec_mod TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_detalle_hoja_ruta
        PRIMARY KEY (id_detalle_hoja_ruta),

    CONSTRAINT fk_detalle_hoja_ruta_hoja
        FOREIGN KEY (id_hoja_ruta)
        REFERENCES logistica.hoja_ruta (id_hoja_ruta),

    CONSTRAINT fk_detalle_hoja_ruta_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES administracion.pedido (id_pedido),

    CONSTRAINT uq_detalle_hoja_ruta_pedido
        UNIQUE (id_pedido),

    CONSTRAINT uq_detalle_hoja_ruta_relacion
        UNIQUE (id_detalle_hoja_ruta, id_hoja_ruta),

    CONSTRAINT ck_detalle_hoja_ruta_estado
        CHECK (estado IN ('A', 'I', 'E'))
);


-- =========================================================
-- 6. LOGISTICA.ASIGNACION_TRANSPORTE
-- =========================================================

CREATE TABLE logistica.asignacion_transporte (
    id_asignacion_transporte INTEGER GENERATED BY DEFAULT AS IDENTITY,

    id_hoja_ruta INTEGER NOT NULL,
    id_vehiculo INTEGER NOT NULL,
    legajo_conductor VARCHAR(20) NOT NULL,

    fecha_asignacion TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    observaciones VARCHAR(1000),

    estado CHAR(1) NOT NULL DEFAULT 'A',

    usu_alta VARCHAR(20) NOT NULL,
    fec_alta TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usu_mod VARCHAR(20),
    fec_mod TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_asignacion_transporte
        PRIMARY KEY (id_asignacion_transporte),

    CONSTRAINT fk_asignacion_hoja_ruta
        FOREIGN KEY (id_hoja_ruta)
        REFERENCES logistica.hoja_ruta (id_hoja_ruta),

    CONSTRAINT fk_asignacion_vehiculo
        FOREIGN KEY (id_vehiculo)
        REFERENCES transporte.vehiculo (id_vehiculo),

    CONSTRAINT fk_asignacion_conductor
        FOREIGN KEY (legajo_conductor)
        REFERENCES transporte.conductor (legajo),

    CONSTRAINT ck_asignacion_transporte_estado
        CHECK (estado IN ('A', 'I', 'E'))
);


-- Una hoja de ruta no puede tener dos asignaciones activas.
CREATE UNIQUE INDEX uq_asignacion_hoja_activa
    ON logistica.asignacion_transporte (id_hoja_ruta)
    WHERE estado = 'A';


-- Un vehículo no puede estar asignado simultáneamente
-- a más de una hoja de ruta activa.
CREATE UNIQUE INDEX uq_asignacion_vehiculo_activo
    ON logistica.asignacion_transporte (id_vehiculo)
    WHERE estado = 'A';


-- Un conductor no puede estar asignado simultáneamente
-- a más de una hoja de ruta activa.
CREATE UNIQUE INDEX uq_asignacion_conductor_activo
    ON logistica.asignacion_transporte (legajo_conductor)
    WHERE estado = 'A';


-- =========================================================
-- 7. LOGISTICA.PARADA_HOJA_RUTA
-- =========================================================

CREATE TABLE logistica.parada_hoja_ruta (
    id_parada INTEGER GENERATED BY DEFAULT AS IDENTITY,

    id_hoja_ruta INTEGER NOT NULL,
    id_detalle_hoja_ruta INTEGER NOT NULL,

    orden_parada INTEGER NOT NULL,

    domicilio VARCHAR(200),
    localidad VARCHAR(100),
    provincia VARCHAR(100),

    observaciones VARCHAR(1000),

    estado CHAR(1) NOT NULL DEFAULT 'A',

    usu_alta VARCHAR(20) NOT NULL,
    fec_alta TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usu_mod VARCHAR(20),
    fec_mod TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_parada_hoja_ruta PRIMARY KEY (id_parada),

    CONSTRAINT fk_parada_hoja_ruta_detalle
        FOREIGN KEY (id_detalle_hoja_ruta, id_hoja_ruta)
        REFERENCES logistica.detalle_hoja_ruta
            (id_detalle_hoja_ruta, id_hoja_ruta),

    CONSTRAINT uq_parada_detalle
        UNIQUE (id_detalle_hoja_ruta),

    CONSTRAINT uq_parada_orden
        UNIQUE (id_hoja_ruta, orden_parada),

    CONSTRAINT ck_parada_orden
        CHECK (orden_parada > 0),

    CONSTRAINT ck_parada_estado
        CHECK (estado IN ('A', 'I', 'E'))
);


-- =========================================================
-- 8. TRANSPORTE.ENTREGA
-- =========================================================

CREATE TABLE transporte.entrega (
    id_entrega INTEGER GENERATED BY DEFAULT AS IDENTITY,

    id_parada INTEGER NOT NULL,

    fecha_entrega TIMESTAMP WITHOUT TIME ZONE,

    estado_entrega CHAR(1) NOT NULL DEFAULT 'P',

    novedades TEXT,

    estado CHAR(1) NOT NULL DEFAULT 'A',

    usu_alta VARCHAR(20) NOT NULL,
    fec_alta TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usu_mod VARCHAR(20),
    fec_mod TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_entrega PRIMARY KEY (id_entrega),

    CONSTRAINT fk_entrega_parada
        FOREIGN KEY (id_parada)
        REFERENCES logistica.parada_hoja_ruta (id_parada),

    CONSTRAINT ck_entrega_estado
        CHECK (estado IN ('A', 'I', 'E')),

    CONSTRAINT ck_entrega_estado_entrega
        CHECK (estado_entrega IN ('P', 'E', 'N', 'R'))
);


-- =========================================================
-- 9. VALIDAR PEDIDOS AL INCORPORARLOS A UNA HOJA DE RUTA
-- =========================================================

CREATE OR REPLACE FUNCTION logistica.fn_validar_pedido_hoja_ruta()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = logistica, pg_temp
AS $$
DECLARE
    v_estado_pedido CHAR(1);
    v_estado_hoja CHAR(1);
BEGIN
    SELECT p.estado
      INTO v_estado_pedido
      FROM administracion.pedido p
     WHERE p.id_pedido = NEW.id_pedido
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'El pedido % no existe.', NEW.id_pedido;
    END IF;

    IF v_estado_pedido <> 'L' THEN
        RAISE EXCEPTION
            'El pedido % no puede incorporarse. Su estado actual es %, debe estar en estado L.',
            NEW.id_pedido, v_estado_pedido;
    END IF;

    SELECT h.estado
      INTO v_estado_hoja
      FROM logistica.hoja_ruta h
     WHERE h.id_hoja_ruta = NEW.id_hoja_ruta
     FOR UPDATE;

    IF NOT FOUND OR v_estado_hoja <> 'A' THEN
        RAISE EXCEPTION
            'La hoja de ruta debe existir y estar activa para incorporar pedidos.';
    END IF;

    IF EXISTS (
        SELECT 1
          FROM logistica.detalle_hoja_ruta d
          JOIN logistica.hoja_ruta h
            ON h.id_hoja_ruta = d.id_hoja_ruta
         WHERE d.id_pedido = NEW.id_pedido
           AND d.estado = 'A'
           AND h.estado = 'A'
           AND (
                TG_OP = 'INSERT'
                OR d.id_detalle_hoja_ruta <> NEW.id_detalle_hoja_ruta
           )
    ) THEN
        RAISE EXCEPTION
            'El pedido % ya está incorporado en otra hoja de ruta activa.',
            NEW.id_pedido;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_pedido_hoja_ruta
BEFORE INSERT OR UPDATE OF id_pedido, id_hoja_ruta
ON logistica.detalle_hoja_ruta
FOR EACH ROW
EXECUTE FUNCTION logistica.fn_validar_pedido_hoja_ruta();


-- =========================================================
-- 10. VALIDAR CONDUCTOR Y VEHICULO EN LA ASIGNACION
-- =========================================================

CREATE OR REPLACE FUNCTION logistica.fn_validar_asignacion_transporte()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = logistica, pg_temp
AS $$
DECLARE
    v_id_rol INTEGER;
    v_estado_empleado CHAR(1);
    v_estado_conductor CHAR(1);
    v_estado_vehiculo CHAR(1);
BEGIN
    SELECT rh.id_rol, rh.estado, c.estado
      INTO v_id_rol, v_estado_empleado, v_estado_conductor
      FROM transporte.conductor c
      JOIN administracion.recursos_humanos rh
        ON rh.legajo = c.legajo
     WHERE c.legajo = NEW.legajo_conductor;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'El conductor con legajo % no está registrado.',
            NEW.legajo_conductor;
    END IF;

    IF v_id_rol <> 17 THEN
        RAISE EXCEPTION
            'El empleado % no tiene el rol de Chofer (17).',
            NEW.legajo_conductor;
    END IF;

    IF v_estado_empleado <> 'A' OR v_estado_conductor <> 'A' THEN
        RAISE EXCEPTION
            'El conductor % no está activo.',
            NEW.legajo_conductor;
    END IF;

    SELECT v.estado
      INTO v_estado_vehiculo
      FROM transporte.vehiculo v
     WHERE v.id_vehiculo = NEW.id_vehiculo;

    IF NOT FOUND OR v_estado_vehiculo <> 'A' THEN
        RAISE EXCEPTION
            'El vehículo seleccionado no existe o no está activo.';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_asignacion_transporte
BEFORE INSERT OR UPDATE OF id_vehiculo, legajo_conductor
ON logistica.asignacion_transporte
FOR EACH ROW
EXECUTE FUNCTION logistica.fn_validar_asignacion_transporte();


