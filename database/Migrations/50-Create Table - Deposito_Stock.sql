CREATE TABLE deposito.stock (
    id_stock INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_lote_producto INTEGER NOT NULL,

    cantidad_reservada NUMERIC(15,3) NOT NULL DEFAULT 0,
    cantidad_consumida NUMERIC(15,3) NOT NULL DEFAULT 0,

    estado CHAR(1) NOT NULL DEFAULT 'A',

    usu_alta VARCHAR(50) NOT NULL,
    fec_alta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    usu_mod VARCHAR(50),
    fec_mod TIMESTAMP,

    CONSTRAINT pk_stock
        PRIMARY KEY (id_stock),

    CONSTRAINT uq_stock_lote
        UNIQUE (id_lote_producto),

    CONSTRAINT fk_stock_lote
        FOREIGN KEY (id_lote_producto)
        REFERENCES produccion.lote_producto(id_lote_producto),

    CONSTRAINT ck_stock_reservada
        CHECK (cantidad_reservada >= 0),

    CONSTRAINT ck_stock_consumida
        CHECK (cantidad_consumida >= 0),

    CONSTRAINT ck_stock_estado
        CHECK (estado IN ('A', 'I', 'E'))
);