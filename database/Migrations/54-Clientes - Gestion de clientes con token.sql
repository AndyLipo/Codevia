-- ---------------------------------------------------------------------
-- 8. LISTAR CLIENTES (administracion.cliente)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION usuarios.listar_clientes(p_token UUID)
RETURNS TABLE(
    id_cliente               integer,
    tipo_cliente             text,
    tipo_cliente_nombre      text,
    nombre_razon_social      text,
    tipo_documento           text,
    nro_documento            text,
    cuit                     text,
    telefono                 text,
    email                    text,
    domicilio                text,
    localidad                text,
    provincia                text,
    codigo_postal            text,
    observaciones            text,
    estado                   text,
    usu_alta                 text,
    fec_alta                 timestamp,
    usu_mod                  text,
    fec_mod                  timestamp,
    categoria_cliente        text,
    categoria_cliente_nombre text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'administracion', 'usuarios', 'extensions', 'public'
AS $$
    SELECT
        c.id_cliente::integer,
        trim(c.tipo_cliente)::text AS tipo_cliente,
        coalesce(tc_info.nombre, trim(c.tipo_cliente))::text AS tipo_cliente_nombre,
        c.nombre_razon_social::text,
        c.tipo_documento::text,
        c.nro_documento::text,
        c.cuit::text,
        c.telefono::text,
        c.email::text,
        c.domicilio::text,
        c.localidad::text,
        c.provincia::text,
        c.codigo_postal::text,
        c.observaciones::text,
        trim(c.estado)::text AS estado,
        c.usu_alta::text,
        c.fec_alta,
        c.usu_mod::text,
        c.fec_mod,
        trim(c.categoria_cliente)::text AS categoria_cliente,
        coalesce(tcc_info.nombre, trim(c.categoria_cliente))::text AS categoria_cliente_nombre
    FROM administracion.cliente c
    LEFT JOIN LATERAL (
        SELECT ext.nombre
        FROM administracion.tipo_cliente tc
        CROSS JOIN LATERAL usuarios.fn_extraer_tipo_cliente(to_jsonb(tc)) ext
        WHERE ext.codigo = trim(c.tipo_cliente)
        LIMIT 1
    ) tc_info ON true
    LEFT JOIN LATERAL (
        SELECT ext.nombre
        FROM administracion.tipo_categoria_cliente tcc
        CROSS JOIN LATERAL usuarios.fn_extraer_categoria_cliente(to_jsonb(tcc)) ext
        WHERE c.categoria_cliente IS NOT NULL
          AND ext.codigo = trim(c.categoria_cliente)
        LIMIT 1
    ) tcc_info ON true
    WHERE usuarios.fn_puede_gestionar_clientes(p_token)
    ORDER BY c.id_cliente ASC;
$$;

-- ---------------------------------------------------------------------
-- 9. CREAR CLIENTE EN administracion.cliente
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION usuarios.crear_cliente(
    p_token               UUID,
    p_tipo_cliente        TEXT,
    p_nombre_razon_social TEXT,
    p_tipo_documento      TEXT DEFAULT NULL,
    p_nro_documento       TEXT DEFAULT NULL,
    p_cuit                TEXT DEFAULT NULL,
    p_telefono            TEXT DEFAULT NULL,
    p_email               TEXT DEFAULT NULL,
    p_domicilio           TEXT DEFAULT NULL,
    p_localidad           TEXT DEFAULT NULL,
    p_provincia           TEXT DEFAULT NULL,
    p_codigo_postal       TEXT DEFAULT NULL,
    p_observaciones       TEXT DEFAULT NULL,
    p_categoria_cliente   TEXT DEFAULT NULL,
    p_estado              TEXT DEFAULT 'A'
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'administracion', 'usuarios', 'extensions', 'public'
AS $$
DECLARE
    v_actor_id       integer;
    v_actor_login    text;
    v_tipo_cliente   text := upper(trim(coalesce(p_tipo_cliente, '')));
    v_nombre         text := trim(coalesce(p_nombre_razon_social, ''));
    v_tipo_doc       text := nullif(upper(trim(coalesce(p_tipo_documento, ''))), '');
    v_nro_doc        text := nullif(trim(coalesce(p_nro_documento, '')), '');
    v_cuit_digits    text := regexp_replace(coalesce(p_cuit, ''), '\D', '', 'g');
    v_cuit_formatted text;
    v_categoria      text := nullif(upper(trim(coalesce(p_categoria_cliente, ''))), '');
    v_estado         text := coalesce(nullif(upper(trim(p_estado)), ''), 'A');
    v_new_row        administracion.cliente%ROWTYPE;
BEGIN
    v_actor_id := usuarios.fn_usuario_de_token(p_token);

    IF NOT usuarios.fn_puede_gestionar_clientes(p_token) THEN
        RAISE EXCEPTION 'No autorizado para gestionar clientes';
    END IF;

    SELECT u.usuario_login INTO v_actor_login
    FROM usuarios.usuarios u
    WHERE u.id_usuario = v_actor_id;

    IF v_tipo_cliente = '' OR length(v_tipo_cliente) > 1 THEN
        RAISE EXCEPTION 'Debe seleccionar un tipo de cliente válido (1 carácter)';
    END IF;

    IF v_nombre = '' THEN
        RAISE EXCEPTION 'El nombre o razón social es obligatorio';
    END IF;

    IF length(v_nombre) > 150 THEN
        RAISE EXCEPTION 'El nombre o razón social no puede superar los 150 caracteres';
    END IF;

    IF v_categoria IS NOT NULL AND length(v_categoria) > 3 THEN
        RAISE EXCEPTION 'La categoría de cliente no puede superar los 3 caracteres';
    END IF;

    IF v_estado NOT IN ('A', 'I', 'E') THEN
        RAISE EXCEPTION 'Estado inválido (valores permitidos: A, I, E)';
    END IF;

    IF v_cuit_digits <> '' THEN
        IF length(v_cuit_digits) <> 11 THEN
            RAISE EXCEPTION 'El CUIT debe contener exactamente 11 dígitos numéricos';
        END IF;
        v_cuit_formatted := substr(v_cuit_digits, 1, 2) || '-' || substr(v_cuit_digits, 3, 8) || '-' || substr(v_cuit_digits, 11, 1);

        IF EXISTS (
            SELECT 1
            FROM administracion.cliente c
            WHERE regexp_replace(coalesce(c.cuit, ''), '\D', '', 'g') = v_cuit_digits
        ) THEN
            RAISE EXCEPTION 'Ya existe un cliente registrado con el CUIT %', v_cuit_formatted;
        END IF;
    ELSE
        v_cuit_formatted := NULL;
    END IF;

    IF v_nro_doc IS NOT NULL AND EXISTS (
        SELECT 1
        FROM administracion.cliente c
        WHERE upper(trim(coalesce(c.nro_documento, ''))) = upper(v_nro_doc)
          AND coalesce(upper(trim(c.tipo_documento)), '') = coalesce(v_tipo_doc, '')
    ) THEN
        RAISE EXCEPTION 'Ya existe un cliente con ese documento (% %)', coalesce(v_tipo_doc, 'DOC'), v_nro_doc;
    END IF;

    INSERT INTO administracion.cliente (
        tipo_cliente,
        nombre_razon_social,
        tipo_documento,
        nro_documento,
        cuit,
        telefono,
        email,
        domicilio,
        localidad,
        provincia,
        codigo_postal,
        observaciones,
        estado,
        usu_alta,
        fec_alta,
        categoria_cliente
    ) VALUES (
        v_tipo_cliente,
        v_nombre,
        v_tipo_doc,
        v_nro_doc,
        v_cuit_formatted,
        nullif(trim(coalesce(p_telefono, '')), ''),
        nullif(lower(trim(coalesce(p_email, ''))), ''),
        nullif(trim(coalesce(p_domicilio, '')), ''),
        nullif(trim(coalesce(p_localidad, '')), ''),
        nullif(trim(coalesce(p_provincia, '')), ''),
        nullif(trim(coalesce(p_codigo_postal, '')), ''),
        nullif(trim(coalesce(p_observaciones, '')), ''),
        v_estado,
        coalesce(v_actor_login, 'SISTEMA'),
        now(),
        v_categoria
    )
    RETURNING * INTO v_new_row;

    INSERT INTO administracion.cliente_historial (
        id_cliente,
        accion,
        estado_anterior,
        estado_nuevo,
        detalle,
        datos_snapshot,
        usuario,
        fecha
    ) VALUES (
        v_new_row.id_cliente,
        'ALTA',
        NULL,
        v_new_row.estado,
        format('Alta de cliente "%s" (Tipo: %s%s)',
            v_new_row.nombre_razon_social,
            trim(v_new_row.tipo_cliente),
            CASE WHEN v_new_row.categoria_cliente IS NOT NULL THEN ', Categoría: ' || trim(v_new_row.categoria_cliente) ELSE '' END
        ),
        to_jsonb(v_new_row),
        coalesce(v_actor_login, 'SISTEMA'),
        now()
    );

    RETURN v_new_row.id_cliente;
END;
$$;

-- ---------------------------------------------------------------------
-- 10. ACTUALIZAR CLIENTE EN administracion.cliente
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION usuarios.actualizar_cliente(
    p_token               UUID,
    p_id_cliente          INTEGER,
    p_tipo_cliente        TEXT,
    p_nombre_razon_social TEXT,
    p_tipo_documento      TEXT DEFAULT NULL,
    p_nro_documento       TEXT DEFAULT NULL,
    p_cuit                TEXT DEFAULT NULL,
    p_telefono            TEXT DEFAULT NULL,
    p_email               TEXT DEFAULT NULL,
    p_domicilio           TEXT DEFAULT NULL,
    p_localidad           TEXT DEFAULT NULL,
    p_provincia           TEXT DEFAULT NULL,
    p_codigo_postal       TEXT DEFAULT NULL,
    p_observaciones       TEXT DEFAULT NULL,
    p_categoria_cliente   TEXT DEFAULT NULL,
    p_estado              TEXT DEFAULT 'A'
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'administracion', 'usuarios', 'extensions', 'public'
AS $$
DECLARE
    v_actor_id       integer;
    v_actor_login    text;
    v_old_row        administracion.cliente%ROWTYPE;
    v_new_row        administracion.cliente%ROWTYPE;
    v_tipo_cliente   text := upper(trim(coalesce(p_tipo_cliente, '')));
    v_nombre         text := trim(coalesce(p_nombre_razon_social, ''));
    v_tipo_doc       text := nullif(upper(trim(coalesce(p_tipo_documento, ''))), '');
    v_nro_doc        text := nullif(trim(coalesce(p_nro_documento, '')), '');
    v_cuit_digits    text := regexp_replace(coalesce(p_cuit, ''), '\D', '', 'g');
    v_cuit_formatted text;
    v_categoria      text := nullif(upper(trim(coalesce(p_categoria_cliente, ''))), '');
    v_estado         text := coalesce(nullif(upper(trim(p_estado)), ''), 'A');
    v_cambios        text[] := ARRAY[]::text[];
    v_accion         text := 'MODIFICACION';
    v_detalle        text;
BEGIN
    v_actor_id := usuarios.fn_usuario_de_token(p_token);

    IF NOT usuarios.fn_puede_gestionar_clientes(p_token) THEN
        RAISE EXCEPTION 'No autorizado para modificar clientes';
    END IF;

    SELECT u.usuario_login INTO v_actor_login
    FROM usuarios.usuarios u
    WHERE u.id_usuario = v_actor_id;

    SELECT * INTO v_old_row
    FROM administracion.cliente c
    WHERE c.id_cliente = p_id_cliente;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontró el cliente #%', p_id_cliente;
    END IF;

    IF v_tipo_cliente = '' OR length(v_tipo_cliente) > 1 THEN
        RAISE EXCEPTION 'Debe seleccionar un tipo de cliente válido (1 carácter)';
    END IF;

    IF v_nombre = '' THEN
        RAISE EXCEPTION 'El nombre o razón social es obligatorio';
    END IF;

    IF v_estado NOT IN ('A', 'I', 'E') THEN
        RAISE EXCEPTION 'Estado inválido (valores permitidos: A, I, E)';
    END IF;

    IF v_cuit_digits <> '' THEN
        IF length(v_cuit_digits) <> 11 THEN
            RAISE EXCEPTION 'El CUIT debe contener exactamente 11 dígitos numéricos';
        END IF;
        v_cuit_formatted := substr(v_cuit_digits, 1, 2) || '-' || substr(v_cuit_digits, 3, 8) || '-' || substr(v_cuit_digits, 11, 1);

        IF EXISTS (
            SELECT 1
            FROM administracion.cliente c
            WHERE regexp_replace(coalesce(c.cuit, ''), '\D', '', 'g') = v_cuit_digits
              AND c.id_cliente <> p_id_cliente
        ) THEN
            RAISE EXCEPTION 'Ya existe otro cliente registrado con el CUIT %', v_cuit_formatted;
        END IF;
    ELSE
        v_cuit_formatted := NULL;
    END IF;

    IF v_nro_doc IS NOT NULL AND EXISTS (
        SELECT 1
        FROM administracion.cliente c
        WHERE upper(trim(coalesce(c.nro_documento, ''))) = upper(v_nro_doc)
          AND coalesce(upper(trim(c.tipo_documento)), '') = coalesce(v_tipo_doc, '')
          AND c.id_cliente <> p_id_cliente
    ) THEN
        RAISE EXCEPTION 'Ya existe otro cliente con ese documento (% %)', coalesce(v_tipo_doc, 'DOC'), v_nro_doc;
    END IF;

    -- Detectar qué campos cambiaron para el historial
    IF trim(coalesce(v_old_row.tipo_cliente, '')) <> v_tipo_cliente THEN
        v_cambios := array_append(v_cambios, format('Tipo (%s -> %s)', trim(coalesce(v_old_row.tipo_cliente, '—')), v_tipo_cliente));
    END IF;
    IF coalesce(v_old_row.nombre_razon_social, '') <> v_nombre THEN
        v_cambios := array_append(v_cambios, 'Razón social');
    END IF;
    IF coalesce(trim(v_old_row.categoria_cliente), '') <> coalesce(v_categoria, '') THEN
        v_cambios := array_append(v_cambios, format('Categoría (%s -> %s)', coalesce(trim(v_old_row.categoria_cliente), '—'), coalesce(v_categoria, '—')));
    END IF;
    IF coalesce(v_old_row.tipo_documento, '') <> coalesce(v_tipo_doc, '') OR coalesce(v_old_row.nro_documento, '') <> coalesce(v_nro_doc, '') THEN
        v_cambios := array_append(v_cambios, 'Documento');
    END IF;
    IF regexp_replace(coalesce(v_old_row.cuit, ''), '\D', '', 'g') <> v_cuit_digits THEN
        v_cambios := array_append(v_cambios, 'CUIT');
    END IF;
    IF coalesce(v_old_row.telefono, '') <> coalesce(nullif(trim(coalesce(p_telefono, '')), ''), '') THEN
        v_cambios := array_append(v_cambios, 'Teléfono');
    END IF;
    IF coalesce(v_old_row.email, '') <> coalesce(nullif(lower(trim(coalesce(p_email, ''))), ''), '') THEN
        v_cambios := array_append(v_cambios, 'Email');
    END IF;
    IF coalesce(v_old_row.domicilio, '') <> coalesce(nullif(trim(coalesce(p_domicilio, '')), ''), '')
       OR coalesce(v_old_row.localidad, '') <> coalesce(nullif(trim(coalesce(p_localidad, '')), ''), '')
       OR coalesce(v_old_row.provincia, '') <> coalesce(nullif(trim(coalesce(p_provincia, '')), ''), '')
       OR coalesce(v_old_row.codigo_postal, '') <> coalesce(nullif(trim(coalesce(p_codigo_postal, '')), ''), '') THEN
        v_cambios := array_append(v_cambios, 'Domicilio / Ubicación');
    END IF;
    IF coalesce(v_old_row.observaciones, '') <> coalesce(nullif(trim(coalesce(p_observaciones, '')), ''), '') THEN
        v_cambios := array_append(v_cambios, 'Observaciones');
    END IF;
    IF trim(coalesce(v_old_row.estado, 'A')) <> v_estado THEN
        v_cambios := array_append(v_cambios, format('Estado (%s -> %s)', trim(coalesce(v_old_row.estado, 'A')), v_estado));
        IF v_estado = 'E' THEN
            v_accion := 'BAJA';
        ELSIF v_estado = 'I' THEN
            v_accion := 'INACTIVACION';
        ELSIF v_estado = 'A' AND trim(coalesce(v_old_row.estado, 'A')) <> 'A' THEN
            v_accion := 'REACTIVACION';
        END IF;
    END IF;

    UPDATE administracion.cliente
    SET tipo_cliente        = v_tipo_cliente,
        nombre_razon_social = v_nombre,
        tipo_documento      = v_tipo_doc,
        nro_documento       = v_nro_doc,
        cuit                = v_cuit_formatted,
        telefono            = nullif(trim(coalesce(p_telefono, '')), ''),
        email               = nullif(lower(trim(coalesce(p_email, ''))), ''),
        domicilio           = nullif(trim(coalesce(p_domicilio, '')), ''),
        localidad           = nullif(trim(coalesce(p_localidad, '')), ''),
        provincia           = nullif(trim(coalesce(p_provincia, '')), ''),
        codigo_postal       = nullif(trim(coalesce(p_codigo_postal, '')), ''),
        observaciones       = nullif(trim(coalesce(p_observaciones, '')), ''),
        categoria_cliente   = v_categoria,
        estado              = v_estado,
        usu_mod             = coalesce(v_actor_login, 'SISTEMA'),
        fec_mod             = now()
    WHERE id_cliente = p_id_cliente
    RETURNING * INTO v_new_row;

    IF array_length(v_cambios, 1) IS NULL THEN
        v_detalle := 'Actualización de ficha sin cambios de valores';
    ELSE
        v_detalle := 'Campos actualizados: ' || array_to_string(v_cambios, ', ');
    END IF;

    INSERT INTO administracion.cliente_historial (
        id_cliente,
        accion,
        estado_anterior,
        estado_nuevo,
        detalle,
        datos_snapshot,
        usuario,
        fecha
    ) VALUES (
        v_new_row.id_cliente,
        v_accion,
        v_old_row.estado,
        v_new_row.estado,
        v_detalle,
        to_jsonb(v_new_row),
        coalesce(v_actor_login, 'SISTEMA'),
        now()
    );

    RETURN true;
END;
$$;

-- ---------------------------------------------------------------------
-- 11. CAMBIAR ESTADO RÁPIDO DE CLIENTE (Baja lógica / Inactivar / Reactivar)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION usuarios.cambiar_estado_cliente(
    p_token      UUID,
    p_id_cliente INTEGER,
    p_estado     TEXT,
    p_motivo     TEXT DEFAULT NULL
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'administracion', 'usuarios', 'extensions', 'public'
AS $$
DECLARE
    v_actor_id    integer;
    v_actor_login text;
    v_old_row     administracion.cliente%ROWTYPE;
    v_new_row     administracion.cliente%ROWTYPE;
    v_estado      text := upper(trim(coalesce(p_estado, '')));
    v_accion      text;
    v_detalle     text;
BEGIN
    v_actor_id := usuarios.fn_usuario_de_token(p_token);

    IF NOT usuarios.fn_puede_gestionar_clientes(p_token) THEN
        RAISE EXCEPTION 'No autorizado para cambiar el estado de clientes';
    END IF;

    SELECT u.usuario_login INTO v_actor_login
    FROM usuarios.usuarios u
    WHERE u.id_usuario = v_actor_id;

    IF v_estado NOT IN ('A', 'I', 'E') THEN
        RAISE EXCEPTION 'Estado inválido (valores permitidos: A, I, E)';
    END IF;

    SELECT * INTO v_old_row
    FROM administracion.cliente c
    WHERE c.id_cliente = p_id_cliente;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontró el cliente #%', p_id_cliente;
    END IF;

    UPDATE administracion.cliente
    SET estado  = v_estado,
        usu_mod = coalesce(v_actor_login, 'SISTEMA'),
        fec_mod = now()
    WHERE id_cliente = p_id_cliente
    RETURNING * INTO v_new_row;

    v_accion := CASE
        WHEN v_estado = 'E' THEN 'BAJA'
        WHEN v_estado = 'I' THEN 'INACTIVACION'
        ELSE 'REACTIVACION'
    END;

    v_detalle := CASE
        WHEN v_estado = 'E' THEN 'Baja lógica del cliente (Estado -> Eliminado)'
        WHEN v_estado = 'I' THEN 'Cliente marcado como Inactivo'
        ELSE 'Reactivación del cliente (Estado -> Activo)'
    END;

    IF nullif(trim(coalesce(p_motivo, '')), '') IS NOT NULL THEN
        v_detalle := v_detalle || ' · Motivo: ' || trim(p_motivo);
    END IF;

    INSERT INTO administracion.cliente_historial (
        id_cliente,
        accion,
        estado_anterior,
        estado_nuevo,
        detalle,
        datos_snapshot,
        usuario,
        fecha
    ) VALUES (
        v_new_row.id_cliente,
        v_accion,
        v_old_row.estado,
        v_new_row.estado,
        v_detalle,
        to_jsonb(v_new_row),
        coalesce(v_actor_login, 'SISTEMA'),
        now()
    );

    RETURN true;
END;
$$;

-- ---------------------------------------------------------------------
-- 12. LISTAR HISTORIAL DE CLIENTES (Global o por id_cliente)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION usuarios.listar_historial_clientes(
    p_token      UUID,
    p_id_cliente INTEGER DEFAULT NULL
)
RETURNS TABLE(
    id_historial        bigint,
    id_cliente          integer,
    nombre_razon_social text,
    cuit                text,
    accion              text,
    estado_anterior     text,
    estado_nuevo        text,
    detalle             text,
    usuario             text,
    fecha               timestamp,
    datos_snapshot      jsonb
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'administracion', 'usuarios', 'extensions', 'public'
AS $$
    SELECT
        h.id_historial::bigint,
        h.id_cliente::integer,
        coalesce(c.nombre_razon_social, h.datos_snapshot->>'nombre_razon_social', 'Cliente #' || h.id_cliente)::text AS nombre_razon_social,
        coalesce(c.cuit, h.datos_snapshot->>'cuit', '')::text AS cuit,
        h.accion::text,
        trim(coalesce(h.estado_anterior, ''))::text AS estado_anterior,
        trim(coalesce(h.estado_nuevo, ''))::text AS estado_nuevo,
        h.detalle::text,
        h.usuario::text,
        h.fecha,
        h.datos_snapshot
    FROM administracion.cliente_historial h
    LEFT JOIN administracion.cliente c ON c.id_cliente = h.id_cliente
    WHERE usuarios.fn_puede_gestionar_clientes(p_token)
      AND (p_id_cliente IS NULL OR h.id_cliente = p_id_cliente)
    ORDER BY h.fecha DESC, h.id_historial DESC
    LIMIT 500;
$$;

