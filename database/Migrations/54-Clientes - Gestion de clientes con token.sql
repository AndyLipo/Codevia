-- 54 - Gestión de Clientes (administracion.cliente) con TOKEN e Historial
-- Requiere haber ejecutado antes los scripts 50 y 53.
--
-- Nota: Las funciones RPC se crean en el esquema "usuarios" (que ya está
-- expuesto en la API de Supabase) y operan sobre:
--   - administracion.cliente
--   - administracion.tipo_cliente
--   - administracion.tipo_categoria_cliente
--   - administracion.cliente_historial
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Asegurar que administracion.cliente.id_cliente sea autoincremental
--    si aún no tiene secuencia ni GENERATED AS IDENTITY.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    v_is_identity text;
    v_col_default text;
    v_max_id      integer;
BEGIN
    SELECT c.is_identity, c.column_default
    INTO v_is_identity, v_col_default
    FROM information_schema.columns c
    WHERE c.table_schema = 'administracion'
      AND c.table_name = 'cliente'
      AND c.column_name = 'id_cliente';

    IF v_is_identity = 'NO' AND v_col_default IS NULL THEN
        EXECUTE 'ALTER TABLE administracion.cliente ALTER COLUMN id_cliente ADD GENERATED BY DEFAULT AS IDENTITY';
        SELECT coalesce(max(id_cliente), 0) + 1 INTO v_max_id FROM administracion.cliente;
        EXECUTE format('ALTER TABLE administracion.cliente ALTER COLUMN id_cliente RESTART WITH %s', v_max_id);
    END IF;
END;
$$;

-- ---------------------------------------------------------------------
-- 2. Tabla de historial de clientes (altas, modificaciones, bajas, etc.)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS administracion.cliente_historial (
    id_historial    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_cliente      INTEGER NOT NULL,
    accion          VARCHAR(30) NOT NULL, -- 'ALTA', 'MODIFICACION', 'BAJA', 'INACTIVACION', 'REACTIVACION'
    estado_anterior CHAR(1),
    estado_nuevo    CHAR(1),
    detalle         TEXT,
    datos_snapshot  JSONB,
    usuario         VARCHAR(50) NOT NULL,
    fecha           TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_cliente_historial_id_cliente
    ON administracion.cliente_historial (id_cliente, fecha DESC);

-- Poblar historial inicial para clientes ya existentes en administracion.cliente
INSERT INTO administracion.cliente_historial (
    id_cliente,
    accion,
    estado_anterior,
    estado_nuevo,
    detalle,
    datos_snapshot,
    usuario,
    fecha
)
SELECT
    c.id_cliente,
    'ALTA',
    NULL,
    c.estado,
    'Registro de alta inicial del cliente',
    to_jsonb(c),
    coalesce(nullif(trim(c.usu_alta), ''), 'SISTEMA'),
    coalesce(c.fec_alta, now())
FROM administracion.cliente c
WHERE NOT EXISTS (
    SELECT 1
    FROM administracion.cliente_historial h
    WHERE h.id_cliente = c.id_cliente
      AND h.accion = 'ALTA'
);

-- Si algún cliente existente ya tenía fec_mod, registrar también su última modificación
INSERT INTO administracion.cliente_historial (
    id_cliente,
    accion,
    estado_anterior,
    estado_nuevo,
    detalle,
    datos_snapshot,
    usuario,
    fecha
)
SELECT
    c.id_cliente,
    CASE
        WHEN c.estado = 'E' THEN 'BAJA'
        WHEN c.estado = 'I' THEN 'INACTIVACION'
        ELSE 'MODIFICACION'
    END,
    c.estado,
    c.estado,
    'Última modificación registrada previamente en el padrón',
    to_jsonb(c),
    coalesce(nullif(trim(c.usu_mod), ''), coalesce(nullif(trim(c.usu_alta), ''), 'SISTEMA')),
    c.fec_mod
FROM administracion.cliente c
WHERE c.fec_mod IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM administracion.cliente_historial h
      WHERE h.id_cliente = c.id_cliente
        AND h.accion <> 'ALTA'
  );

-- ---------------------------------------------------------------------
-- 3. Habilitar el módulo 'clients' por defecto en Administrador (id_rol = 1)
-- ---------------------------------------------------------------------
UPDATE usuarios.roles
SET modulos = array_append(modulos, 'clients')
WHERE id_rol = 1
  AND NOT ('clients' = ANY(coalesce(modulos, ARRAY[]::TEXT[])));

-- ---------------------------------------------------------------------
-- 4. Helper de autorización para Gestión de Clientes
--    Permite operar a id_rol = 1 o a cualquier rol que tenga 'clients'
--    asignado en usuarios.roles.modulos (desde Parámetros -> Permisos).
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION usuarios.fn_puede_gestionar_clientes(p_token UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'administracion', 'usuarios', 'extensions', 'public'
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM usuarios.usuarios u
        LEFT JOIN usuarios.roles r ON r.id_rol = u.id_rol
        WHERE u.id_usuario = usuarios.fn_usuario_de_token(p_token)
          AND u.estado = 'A'
          AND (
              u.id_rol = 1
              OR 'clients' = ANY(coalesce(r.modulos, ARRAY[]::TEXT[]))
          )
    );
$$;

REVOKE ALL ON FUNCTION usuarios.fn_puede_gestionar_clientes(UUID) FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------------
-- 5. Helpers internos para extraer código y nombre de tipo_cliente y
--    tipo_categoria_cliente sin importar cómo se llamen sus columnas.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION usuarios.fn_extraer_tipo_cliente(p_row JSONB)
RETURNS TABLE(codigo text, nombre text, descripcion text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'information_schema', 'administracion', 'usuarios', 'public'
AS $$
    WITH cols AS (
        SELECT
            kv.key,
            trim(kv.value) AS val,
            ic.character_maximum_length AS max_len,
            ic.ordinal_position AS pos
        FROM jsonb_each_text(p_row) kv
        LEFT JOIN information_schema.columns ic
          ON ic.table_schema = 'administracion'
         AND ic.table_name = 'tipo_cliente'
         AND ic.column_name = kv.key
        WHERE lower(kv.key) NOT IN (
            'estado', 'usu_alta', 'fec_alta', 'usu_mod', 'fec_mod',
            'created_at', 'updated_at', 'activo'
        )
          AND nullif(trim(kv.value), '') IS NOT NULL
    ),
    chosen_code AS (
        SELECT c.key, left(c.val, 1) AS code_val
        FROM cols c
        ORDER BY
            CASE
                WHEN c.max_len = 1 THEN 0
                WHEN length(c.val) = 1 AND c.val ~ '^[A-Za-z]$' THEN 1
                WHEN lower(c.key) IN ('codigo', 'tipo_cliente', 'cod_tipo_cliente', 'cod_tipo', 'letra', 'abrev', 'sigla', 'tipo', 'id_tipo_cliente', 'id')
                     AND length(c.val) = 1 THEN 2
                WHEN length(c.val) = 1 THEN 3
                ELSE 4
            END,
            c.pos ASC NULLS LAST
        LIMIT 1
    ),
    chosen_name AS (
        SELECT c.key, c.val AS name_val
        FROM cols c
        LEFT JOIN chosen_code cc ON true
        WHERE c.key IS DISTINCT FROM cc.key
        ORDER BY
            CASE
                WHEN lower(c.key) IN ('nombre', 'descripcion', 'detalle', 'denominacion', 'nombre_tipo', 'desc_tipo', 'tipo')
                     AND length(c.val) > 1 THEN 0
                WHEN coalesce(c.max_len, 100) >= 15 AND length(c.val) > 1 THEN 1
                WHEN length(c.val) > 1 THEN 2
                ELSE 3
            END,
            c.pos ASC NULLS LAST
        LIMIT 1
    )
    SELECT
        coalesce((SELECT code_val FROM chosen_code), '')::text AS codigo,
        coalesce((SELECT name_val FROM chosen_name), (SELECT code_val FROM chosen_code), '')::text AS nombre,
        coalesce((SELECT name_val FROM chosen_name), '')::text AS descripcion;
$$;

CREATE OR REPLACE FUNCTION usuarios.fn_extraer_categoria_cliente(p_row JSONB)
RETURNS TABLE(codigo text, nombre text, descripcion text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'information_schema', 'administracion', 'usuarios', 'public'
AS $$
    WITH cols AS (
        SELECT
            kv.key,
            trim(kv.value) AS val,
            ic.character_maximum_length AS max_len,
            ic.ordinal_position AS pos
        FROM jsonb_each_text(p_row) kv
        LEFT JOIN information_schema.columns ic
          ON ic.table_schema = 'administracion'
         AND ic.table_name = 'tipo_categoria_cliente'
         AND ic.column_name = kv.key
        WHERE lower(kv.key) NOT IN (
            'estado', 'usu_alta', 'fec_alta', 'usu_mod', 'fec_mod',
            'created_at', 'updated_at', 'activo', 'tipo_cliente'
        )
          AND nullif(trim(kv.value), '') IS NOT NULL
    ),
    chosen_code AS (
        SELECT c.key, left(c.val, 3) AS code_val
        FROM cols c
        ORDER BY
            CASE
                WHEN c.max_len = 3 THEN 0
                WHEN length(c.val) BETWEEN 1 AND 3 AND c.val ~ '^[A-Za-z]' THEN 1
                WHEN lower(c.key) IN (
                    'codigo', 'categoria_cliente', 'tipo_categoria_cliente',
                    'cod_categoria_cliente', 'cod_categoria', 'cod_cat',
                    'categoria', 'abrev', 'sigla', 'id_tipo_categoria_cliente',
                    'id_categoria_cliente', 'id_categoria', 'id'
                ) AND length(c.val) <= 3 THEN 2
                WHEN c.max_len BETWEEN 1 AND 5 AND length(c.val) <= 3 THEN 3
                WHEN length(c.val) BETWEEN 1 AND 3 THEN 4
                ELSE 5
            END,
            c.pos ASC NULLS LAST
        LIMIT 1
    ),
    chosen_name AS (
        SELECT c.key, c.val AS name_val
        FROM cols c
        LEFT JOIN chosen_code cc ON true
        WHERE c.key IS DISTINCT FROM cc.key
        ORDER BY
            CASE
                WHEN lower(c.key) IN (
                    'nombre', 'descripcion', 'detalle', 'denominacion',
                    'nombre_categoria', 'desc_categoria', 'categoria'
                ) AND length(c.val) > 1 THEN 0
                WHEN coalesce(c.max_len, 100) >= 15 AND length(c.val) > 1 THEN 1
                WHEN length(c.val) > 3 THEN 2
                ELSE 3
            END,
            c.pos ASC NULLS LAST
        LIMIT 1
    )
    SELECT
        coalesce((SELECT code_val FROM chosen_code), '')::text AS codigo,
        coalesce((SELECT name_val FROM chosen_name), (SELECT code_val FROM chosen_code), '')::text AS nombre,
        coalesce((SELECT name_val FROM chosen_name), '')::text AS descripcion;
$$;

-- ---------------------------------------------------------------------
-- 6. LISTAR OPCIONES DE administracion.tipo_cliente
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION usuarios.listar_tipos_cliente(p_token UUID)
RETURNS TABLE(
    codigo      text,
    nombre      text,
    descripcion text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'administracion', 'usuarios', 'extensions', 'public'
AS $$
    SELECT
        ext.codigo,
        ext.nombre,
        ext.descripcion
    FROM administracion.tipo_cliente tc
    CROSS JOIN LATERAL (SELECT to_jsonb(tc) AS j) sub
    CROSS JOIN LATERAL usuarios.fn_extraer_tipo_cliente(sub.j) ext
    WHERE usuarios.fn_usuario_de_token(p_token) IS NOT NULL
      AND upper(trim(coalesce(sub.j->>'estado', 'A'))) NOT IN ('I', 'E', 'B', '0', 'FALSE')
      AND ext.codigo <> ''
    ORDER BY ext.codigo ASC;
$$;

